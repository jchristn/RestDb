function mapStrings(value, mapper) {
  if (typeof value === 'string') {
    return mapper(value);
  }

  if (Array.isArray(value)) {
    return value.map((entry) => mapStrings(entry, mapper));
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, entry]) => [key, mapStrings(entry, mapper)])
    );
  }

  return value;
}

