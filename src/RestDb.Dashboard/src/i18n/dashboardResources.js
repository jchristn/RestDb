function deepMerge(base, overrides) {
  if (Array.isArray(base)) {
    return overrides ?? base.slice();
  }

  if (base && typeof base === 'object') {
    const result = { ...base };
    Object.entries(overrides || {}).forEach(([key, value]) => {
      result[key] =
        value && typeof value === 'object' && !Array.isArray(value)
          ? deepMerge(base[key] || {}, value)
          : value;
    });
    return result;
  }

  return overrides ?? base;
}

function repairMojibake(value) {
  if (typeof value === 'string') {
    if (!/[ÃÂâæãØÙ]/.test(value)) {
      return value;
    }

    try {
      const bytes = Uint8Array.from(Array.from(value).map((character) => character.charCodeAt(0) & 0xff));
      return new TextDecoder('utf-8', { fatal: false }).decode(bytes);
    } catch {
      return value;
    }
  }

  if (Array.isArray(value)) {
    return value.map((entry) => repairMojibake(entry));
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, entry]) => [key, repairMojibake(entry)])
    );
  }

  return value;
}

